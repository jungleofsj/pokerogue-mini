/*
 * PokeRogue Mini - a small desktop wrapper around the official pokerogue.net
 *
 * One window, Chrome-style tabs at the top: the first tab is the game (always
 * running), further tabs are ordinary web pages (wiki, calculators...).
 * A slim monochrome toolbar doubles as the title bar; a Claude strategy panel
 * (with the weekly legendary pickup strip) attaches to the LEFT of the content.
 *
 * Hotkeys (while the window is focused):
 *   Ctrl+G      toggle tone on/off        Ctrl+M      toggle mute
 *   Ctrl+Down/Up     dim / brighten      Ctrl+Left/Right  window opacity
 *   Ctrl+P      size preset              Ctrl+R      reload active tab
 *   Ctrl+T      new web tab              Ctrl+W      close active web tab
 *   Ctrl+Tab    cycle tabs               Ctrl+L      address bar (new tab if on game)
 * Global (works even when hidden):
 *   Ctrl+Alt+P  boss key - hide/show the window
 *
 * Audio: muted by default; even when unmuted, audio auto-mutes while the
 * window is not focused or hidden.
 */
